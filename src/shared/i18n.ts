const DICTS: Record<Locale, Record<string, string>> = { en: {}, zh: ZH }

/** Translates `key` into `locale`, filling `{name}` placeholders from `vars`. */
export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const text = DICTS[locale][key] ?? key
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
}

export function isLocale(value: unknown): value is Locale {
  return value === 'en' || value === 'zh'
}

/** Best guess from a system language tag such as "zh-CN" or "en-US". */
export function localeFrom(tag: string | undefined): Locale {
  return tag?.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

/** Keys that have a Chinese translation; used by tests to catch typos in keys. */
export function translatedKeys(): string[] {
  return Object.keys(ZH)
}
